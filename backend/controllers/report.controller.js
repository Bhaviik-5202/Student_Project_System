const reportService = require('../services/report.service');
const sendResponse = require('../utils/response');

/**
 * Report Controller
 * Handles the generation, retrieval, and management of system and project reports.
 */

/**
 * Create a new report
 * @route   POST /api/reports
 * @desc    Generate and save a new system or project report
 * @access  Authenticated
 * @param {Object} req - Express request object
 * @param {Object} res - Express response object
 */
exports.createReport = async (req, res) => {
  try {
    const reportData = { ...req.body, generatedBy: req.user.id };
    const { error, data, message } =
      await reportService.createReport(reportData);
    if (error) throw new Error(message);
    sendResponse(res, { success: true, data, message }, 201);
  } catch (error) {
    sendResponse(res, { success: false, message: error.message }, 500);
  }
};

/**
 * Fetch all reports
 * @route   GET /api/reports
 * @desc    Retrieve a list of reports generated by or accessible to the user
 * @access  Admin, Owner
 * @param {Object} req - Express request object
 * @param {Object} res - Express response object
 */
exports.getReports = async (req, res) => {
  try {
    const query = req.user.role === 'admin' ? {} : { generatedBy: req.user.id };
    const { error, data, message } = await reportService.getAllReports(query);
    if (error) throw new Error(message);
    sendResponse(res, { success: true, data, message }, 200);
  } catch (error) {
    sendResponse(res, { success: false, message: error.message }, 500);
  }
};

/**
 * Delete a report
 * @route   DELETE /api/reports/:id
 * @desc    Permanently remove a generated report record
 * @access  Admin, Owner
 * @param {Object} req - Express request object
 * @param {Object} res - Express response object
 */
exports.deleteReport = async (req, res) => {
  try {
    const { error, data, message } = await reportService.deleteReport(
      req.params.id
    );
    if (error) throw new Error(message);
    sendResponse(res, { success: true, data, message }, 200);
  } catch (error) {
    sendResponse(res, { success: false, message: error.message }, 500);
  }
};

/**
 * Update a report
 * @route   PUT /api/reports/:id
 * @desc    Modify metadata or content for an existing report
 * @access  Admin, Owner
 * @param {Object} req - Express request object
 * @param {Object} res - Express response object
 */
exports.updateReport = async (req, res) => {
  try {
    const { error, data, message } = await reportService.updateReport(
      req.params.id,
      req.body
    );
    if (error) throw new Error(message);
    sendResponse(res, { success: true, data, message }, 200);
  } catch (error) {
    sendResponse(res, { success: false, message: error.message }, 500);
  }
};
